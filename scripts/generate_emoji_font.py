#!/usr/bin/env python3
"""Regenerate the OFL Noto Emoji bitmap font (requires fonttools and Node/npx)."""
import hashlib
from pathlib import Path
import subprocess
import tempfile
from urllib.request import urlopen

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[1]
REVISION = "8b0a1d0f5983c89bc2b93f1b5fb55f9e252744b5"
SHA256 = "de6c18832938afc99caf132b39d6a30a19bac7f2e812e28db2535b4608d27551"
URL = f"https://raw.githubusercontent.com/google/fonts/{REVISION}/ofl/notoemoji/NotoEmoji%5Bwght%5D.ttf"


def main():
    with tempfile.TemporaryDirectory(prefix="wio-emoji-") as directory:
        source = Path(directory) / "NotoEmoji.ttf"
        with urlopen(URL, timeout=60) as response:
            payload = response.read()
        if hashlib.sha256(payload).hexdigest() != SHA256:
            raise RuntimeError("Noto Emoji source checksum mismatch")
        source.write_bytes(payload)
        font = instantiateVariableFont(TTFont(source), {"wght": 400}, inplace=False)
        static = Path(directory) / "NotoEmoji-Regular.ttf"
        font.save(static)
        # Invisible presentation controls are handled by UiFont.cpp.
        points = sorted(c for c in font.getBestCmap() if c > 127 and c not in (0x200D, 0xFE0E, 0xFE0F))
        assert 0x1F44D in points
        target = ROOT / "src/lv_font_emoji_14.c"
        subprocess.run([
            "npx", "--yes", "lv_font_conv@1.5.3", "--size", "14", "--bpp", "2",
            "--font", str(static), "--range", ",".join(hex(c) for c in points),
            "--format", "lvgl", "--lv-font-name", "lv_font_emoji_14", "--no-compress",
            "--no-prefilter", "--no-kerning", "--lv-fallback", "lv_font_montserrat_14",
            "-o", str(target),
        ], check=True)
        text = target.read_text()
        text = "#include <lvgl.h>\n\n" + text[text.index("#ifndef LV_FONT_EMOJI_14"): ]
        target.write_text(
            "/* Noto Emoji, Copyright 2013 Google LLC, SIL OFL 1.1.\n"
            " * Generated by scripts/generate_emoji_font.py; see licenses/fonts/NotoEmoji-OFL.txt. */\n"
            + text
        )
        print(f"Generated {len(points)} monochrome glyphs, including U+1F44D")


if __name__ == "__main__":
    main()
